export function getProfessionConfig(
  slug: string
): ProfessionPageConfig | undefined {
  return professionConfigs[slug];
}

export function getProfessionMetadata(slug: string): {
  title: string;
  description: string;
  canonical: string;
  keywords: string[];
} | null {
  const config = professionConfigs[slug];
  if (!config) return null;
  return {
    title: `${config.title} | CELPIP Practice Test`,
    description: config.intro.slice(0, 160),
    canonical: `${baseUrl}/${config.slug}`,
    keywords: [
      `CELPIP for ${config.title.replace("CELPIP for ", "")}`,
      "CELPIP Canada",
      "language test",
    ],
  };
}
